"""
SIH Problem Statement 26145: AI-Based Detection of Cyber Threats in Unidirectional IP Traffic
Module: src.database.models

SQLAlchemy ORM models for Flows, Threat Alerts, and Model Compatibility Status.
Strictly metadata-only: does NOT store packet payloads, decrypted payloads, or raw packets.
"""

from datetime import datetime
from sqlalchemy import (
    Column,
    Integer,
    BigInteger,
    Float,
    String,
    Text,
    DateTime,
    Boolean,
    JSON,
    Index,
    UniqueConstraint,
    func
)
from src.database.database import Base


class FlowModel(Base):
    """
    Represents aggregated unidirectional / bidirectional network flow telemetry.
    Strictly metadata-only (5-tuple, volume, timing, flag statistics).
    """
    __tablename__ = "flows"

    id = Column(Integer, primary_key=True, autoincrement=True)
    flow_id = Column(String(64), unique=True, nullable=False, index=True)
    timestamp = Column(Float, nullable=False, index=True)
    start_time = Column(Float, nullable=False)
    last_seen = Column(Float, nullable=False)

    # 5-Tuple Network Metadata
    src_ip = Column(String(45), nullable=False, index=True)
    dst_ip = Column(String(45), nullable=False, index=True)
    src_port = Column(Integer, nullable=True)
    dst_port = Column(Integer, nullable=True)
    protocol = Column(String(10), nullable=False, index=True)

    # Volumetric & Rate Metrics
    duration = Column(Float, nullable=False)
    total_packets = Column(Integer, nullable=False)
    total_bytes = Column(BigInteger, nullable=False)

    forward_packets = Column(Integer, nullable=False, default=0)
    backward_packets = Column(Integer, nullable=False, default=0)

    forward_bytes = Column(BigInteger, nullable=False, default=0)
    backward_bytes = Column(BigInteger, nullable=False, default=0)

    packets_per_second = Column(Float, nullable=False, default=0.0)
    bytes_per_second = Column(Float, nullable=False, default=0.0)

    # TCP Control Flags
    syn_count = Column(Integer, nullable=False, default=0)
    ack_count = Column(Integer, nullable=False, default=0)
    fin_count = Column(Integer, nullable=False, default=0)
    rst_count = Column(Integer, nullable=False, default=0)
    psh_count = Column(Integer, nullable=False, default=0)
    urg_count = Column(Integer, nullable=False, default=0)

    # Inter-Arrival Timing (IAT) Metrics
    iat_mean = Column(Float, nullable=False, default=0.0)
    iat_std = Column(Float, nullable=False, default=0.0)
    iat_min = Column(Float, nullable=False, default=0.0)
    iat_max = Column(Float, nullable=False, default=0.0)

    # Operational Context
    traffic_context = Column(String(30), nullable=False, default="UNLABELED_LIVE", index=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())

    __table_args__ = (
        Index("idx_flows_src_dst", "src_ip", "dst_ip"),
        Index("idx_flows_timestamp_proto", "timestamp", "protocol"),
    )

    def to_dict(self):
        """Convert ORM model to dictionary."""
        return {
            "id": self.id,
            "flow_id": self.flow_id,
            "timestamp": self.timestamp,
            "start_time": self.start_time,
            "last_seen": self.last_seen,
            "src_ip": self.src_ip,
            "dst_ip": self.dst_ip,
            "src_port": self.src_port,
            "dst_port": self.dst_port,
            "protocol": self.protocol,
            "duration": self.duration,
            "total_packets": self.total_packets,
            "total_bytes": self.total_bytes,
            "forward_packets": self.forward_packets,
            "backward_packets": self.backward_packets,
            "forward_bytes": self.forward_bytes,
            "backward_bytes": self.backward_bytes,
            "packets_per_second": self.packets_per_second,
            "bytes_per_second": self.bytes_per_second,
            "syn_count": self.syn_count,
            "ack_count": self.ack_count,
            "fin_count": self.fin_count,
            "rst_count": self.rst_count,
            "psh_count": self.psh_count,
            "urg_count": self.urg_count,
            "iat_mean": self.iat_mean,
            "iat_std": self.iat_std,
            "iat_min": self.iat_min,
            "iat_max": self.iat_max,
            "traffic_context": self.traffic_context,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class AlertModel(Base):
    """
    Represents an explainable threat detection verdict generated by the Alert Engine.
    Contains detection classification, severity, confidence bands, and supporting evidence.
    """
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    alert_id = Column(String(64), unique=True, nullable=False, index=True)
    timestamp = Column(Float, nullable=False, index=True)

    flow_id = Column(String(64), nullable=False, index=True)

    # 5-Tuple Network Metadata
    src_ip = Column(String(45), nullable=False, index=True)
    dst_ip = Column(String(45), nullable=False, index=True)
    src_port = Column(Integer, nullable=True)
    dst_port = Column(Integer, nullable=True)
    protocol = Column(String(10), nullable=False, index=True)

    # Threat Classification & Triage
    threat_class = Column(String(50), nullable=False, index=True)
    threat_category = Column(String(100), nullable=False)

    confidence = Column(Float, nullable=True)
    confidence_band = Column(String(30), nullable=False, default="LOW_CONFIDENCE")

    severity = Column(String(20), nullable=False, index=True)  # BENIGN, LOW, MEDIUM, HIGH, CRITICAL

    detector = Column(String(100), nullable=False)
    model_status = Column(String(50), nullable=False, default="FULLY_COMPATIBLE")

    # Structured Explainability
    evidence = Column(JSON, nullable=False, default=list)
    evidence_summary = Column(Text, nullable=False, default="")

    recommended_action = Column(Text, nullable=False, default="")
    traffic_context = Column(String(30), nullable=False, default="UNLABELED_LIVE", index=True)

    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())

    __table_args__ = (
        Index("idx_alerts_threat_severity", "threat_class", "severity"),
        Index("idx_alerts_timestamp_desc", timestamp.desc()),
        Index("idx_alerts_src_dst", "src_ip", "dst_ip"),
    )

    def to_dict(self):
        """Convert ORM model to dictionary."""
        return {
            "id": self.id,
            "alert_id": self.alert_id,
            "timestamp": self.timestamp,
            "flow_id": self.flow_id,
            "src_ip": self.src_ip,
            "dst_ip": self.dst_ip,
            "src_port": self.src_port,
            "dst_port": self.dst_port,
            "protocol": self.protocol,
            "threat_class": self.threat_class,
            "threat_category": self.threat_category,
            "confidence": self.confidence,
            "confidence_band": self.confidence_band,
            "severity": self.severity,
            "detector": self.detector,
            "model_status": self.model_status,
            "evidence": self.evidence,
            "evidence_summary": self.evidence_summary,
            "recommended_action": self.recommended_action,
            "traffic_context": self.traffic_context,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class ModelStatusModel(Base):
    """
    Represents the runtime operational and feature compatibility status of threat detection models.
    """
    __tablename__ = "model_status"

    id = Column(Integer, primary_key=True, autoincrement=True)
    model_name = Column(String(50), unique=True, nullable=False, index=True)
    status = Column(String(50), nullable=False)        # PARTIALLY_COMPATIBLE, FULLY_COMPATIBLE, NOT_COMPATIBLE
    compatible = Column(String(50), nullable=False)    # PARTIALLY_COMPATIBLE, FULLY_COMPATIBLE, NOT_COMPATIBLE
    reason = Column(Text, nullable=False)
    updated_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())

    def to_dict(self):
        """Convert ORM model to dictionary."""
        return {
            "id": self.id,
            "model_name": self.model_name,
            "status": self.status,
            "compatible": self.compatible,
            "reason": self.reason,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


class UserModel(Base):
    """
    Represents an authorized operator, analyst, or administrator account.
    Passwords are exclusively stored as salted Argon2id hashes.
    Plaintext passwords are never stored or logged.
    """
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, autoincrement=True)
    user_id = Column(String(64), unique=True, nullable=False, index=True)
    email = Column(String(255), unique=True, nullable=False, index=True)
    hashed_password = Column(String(255), nullable=False)
    full_name = Column(String(100), nullable=False)
    role = Column(String(30), nullable=False, default="analyst")  # "admin", "analyst", "viewer"
    is_active = Column(Boolean, nullable=False, default=True)
    failed_login_attempts = Column(Integer, nullable=False, default=0)
    locked_until = Column(DateTime(timezone=True), nullable=True)
    last_login_at = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())

    def to_dict(self):
        """Convert ORM model to dictionary (strictly excludes hashed_password)."""
        return {
            "id": self.id,
            "user_id": self.user_id,
            "email": self.email,
            "full_name": self.full_name,
            "role": self.role,
            "is_active": self.is_active,
            "last_login_at": self.last_login_at.isoformat() if self.last_login_at else None,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class UserSessionModel(Base):
    """
    Represents an active or revoked authentication session token.
    Enables server-side session revocation upon logout and audit logging.
    """
    __tablename__ = "user_sessions"

    id = Column(Integer, primary_key=True, autoincrement=True)
    session_id = Column(String(64), unique=True, nullable=False, index=True)
    user_id = Column(String(64), nullable=False, index=True)
    token_jti = Column(String(64), unique=True, nullable=False, index=True)
    created_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    expires_at = Column(DateTime(timezone=True), nullable=False, index=True)
    last_active_at = Column(DateTime(timezone=True), nullable=False, server_default=func.now())
    is_revoked = Column(Boolean, nullable=False, default=False, index=True)
    ip_address = Column(String(45), nullable=True)
    user_agent = Column(String(255), nullable=True)
